-- Jalankan di Supabase Dashboard > SQL Editor.
create table if not exists public.works (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null default 'PANTIK',
  category text,
  excerpt text,
  content text not null,
  cover_url text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.works enable row level security;
-- Publik hanya dapat membaca karya yang sudah diterbitkan.
create policy "Public can read published works" on public.works
for select to anon, authenticated using (published = true);
-- Admin yang login dapat mengelola seluruh karya.
create policy "Authenticated admins manage works" on public.works
for all to authenticated using (true) with check (true);
